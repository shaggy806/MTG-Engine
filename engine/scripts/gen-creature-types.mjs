// Regenerates `src/creature-types.ts` from Scryfall's creature-type catalog —
// the authoritative list of every creature type (rule 205.3m).
//
//   npm run gen:creature-types -w engine
//
// The output is checked in, so the engine never needs the network at runtime.
// Only rerun this when a new set adds creature types.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const USER_AGENT = "MTG-Engine-CardAuthoring/1.0";
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "creature-types.ts");

const res = await fetch("https://api.scryfall.com/catalog/creature-types", {
  headers: { "User-Agent": USER_AGENT, Accept: "application/json" },
});
if (!res.ok) {
  console.error(`Scryfall catalog request failed: ${res.status}`);
  process.exit(1);
}
const { data } = await res.json();
const types = [...data].sort((a, b) => a.localeCompare(b));

const lines = [
  "// GENERATED by scripts/gen-creature-types.mjs from Scryfall's creature-type",
  "// catalog — do not edit by hand. Rerun that script to update it.",
  "",
  "/**",
  " * Every creature type (rule 205.3m), alphabetical. What a \"choose a creature",
  " * type\" decision offers — see `AwaitingDecision`'s `choose-creature-type`.",
  " */",
  "export const CREATURE_TYPES: readonly string[] = [",
  ...types.map((t) => `  ${JSON.stringify(t)},`),
  "];",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`wrote src/creature-types.ts (${types.length} creature types)`);
